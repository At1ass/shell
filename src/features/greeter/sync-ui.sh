#!/usr/bin/env bash
# Regenerate the greeter's local UI kit (greeter/ui/*) from the canonical main kit.
#
# The greeter runs as a SEPARATE Quickshell process (greetd, pre-login, `greeter` user)
# with its own module roots (qs.ui / qs.config) and its own theme (GreeterTheme, seeded
# from greeter.json instead of the logged-in user's WallpaperManager/AppConfig). The
# component bodies, however, are identical to the main kit modulo a mechanical substitution:
#   - import qs.src.core.config  ->  import qs.config        (GreeterTheme lives in qs.config)
#   - import qs.src.ui.{feedback,base}  ->  (dropped; same-module in qs.ui)
#   - Theme.  ->  GreeterTheme.   /   Theme[ -> GreeterTheme[
#   - Tokens: AppConfig.fontScale -> a literal (greeter has no AppConfig)
#   - Tokens: the font-family overrides -> empty, so the greeter always takes
#     the pack default rather than a family the logged-out session cannot read
#
# This script is the single source of truth: edit src/ui, then re-run. Do not hand-edit
# greeter/ui/*.qml — changes will be overwritten.
#
# Usage:  src/features/greeter/sync-ui.sh            (run from anywhere)
#         src/features/greeter/sync-ui.sh --check    (generate to a temp dir and
#                                                     diff; prints the number of
#                                                     drifted files, exit 1 if any)
#
# --check is what tools/check.sh calls: the generator stays the single source of
# truth, so the invariant can never disagree with the thing it is checking.
set -euo pipefail

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

# Repo root = two levels up from this script (src/features/greeter -> repo root).
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
SRC="$ROOT/src/ui"
DST="$SCRIPT_DIR/ui"

if [ "$CHECK" -eq 1 ]; then
  REAL="$DST"
  DST="$(mktemp -d)"
  trap 'rm -rf "$DST"' EXIT
fi

# Typography, motion and design profile are read from root-owned greeter.json.
# The generated kit keeps the main component implementations and local config.

HEADER="// GENERATED by src/features/greeter/sync-ui.sh — do not edit. Edit src/ui and re-run."

# component <source-relative-path>
components=(
  "MaterialText.qml:base/MaterialText.qml"
  "MaterialIcon.qml:base/MaterialIcon.qml"
  "MaterialButton.qml:base/MaterialButton.qml"
  "IconButton.qml:base/IconButton.qml"
  "CircleAvatar.qml:base/CircleAvatar.qml"
  "ElevationShadow.qml:base/ElevationShadow.qml"
  "StateLayer.qml:feedback/StateLayer.qml"
  "Surface.qml:containers/Surface.qml"
  "MaterialTextField.qml:inputs/MaterialTextField.qml"
  "MaterialComboBox.qml:inputs/MaterialComboBox.qml"
  "MotionAnimation.qml:base/MotionAnimation.qml"
  "MotionColorAnimation.qml:base/MotionColorAnimation.qml"
)

# Common substitution applied to component files.
substitute() {
  sed -E \
    -e 's|import qs\.src\.core\.config|import qs.config|' \
    -e '/^import qs\.src\.ui\.feedback$/d' \
    -e '/^import qs\.src\.ui\.base$/d' \
    -e '/^import qs\.src\.ui\.containers$/d' \
    -e 's/\bTheme\b/GreeterTheme/g'
}

# Insert HEADER: after a leading `pragma` line if present, else at the very top.
with_header() {
  awk -v hdr="$HEADER" 'NR==1 && $0 ~ /^pragma/ {print; print hdr; next} NR==1 {print hdr} {print}'
}

say() { [ "$CHECK" -eq 1 ] || echo "$@"; }

for entry in "${components[@]}"; do
  out="${entry%%:*}"
  rel="${entry##*:}"
  substitute < "$SRC/$rel" | with_header > "$DST/$out"
  say "  generated ui/$out  <- src/ui/$rel"
done

# Tokens: copy main tokens, fold away the AppConfig dependency. The greeter has
# no AppConfig singleton, so every reference must use GreeterConfig or a literal.
# Values come from GreeterConfig; the greeter never reads the user config.
sed -E \
  -e "s|AppConfig\.fontScale|GreeterConfig.fontScale|" \
  -e "s|AppConfig\.reduceMotion|GreeterConfig.reduceMotion|" \
  -e "s|AppConfig\.motionScale|1.0|" \
  -e "s|AppConfig\.designSystem|GreeterConfig.designSystem|" \
  -e "s|AppConfig\.fontFamily|\"\"|" \
  -e "s|AppConfig\.monoFamily|\"\"|" \
  -e 's|import Quickshell$|import Quickshell\nimport qs.config|' \
  "$ROOT/src/core/config/Tokens.qml" \
  | with_header > "$DST/Tokens.qml"
say "  generated ui/Tokens.qml  <- src/core/config/Tokens.qml (GreeterConfig typography/profile)"

# qmldir is GENERATED from the list above. It used to be hand-maintained, and that
# is exactly how the greeter broke: MotionAnimation/MotionColorAnimation were
# introduced in the main kit and picked up by four generated components, while
# being absent from both the copy list and this module. Every greeter button,
# icon and state layer would have failed to resolve its animation type at
# runtime — on the PRE-LOGIN screen, where there is no way to recover.
# Deriving it from `components` makes that class of drift unrepresentable.
{
  echo "module qs.ui"
  echo
  echo "singleton Tokens 1.0 Tokens.qml"
  for entry in "${components[@]}"; do
    out="${entry%%:*}"
    printf '%s 1.0 %s\n' "${out%.qml}" "$out"
  done
} > "$DST/qmldir"
say "  generated ui/qmldir  <- components list"

# GUARD. The greeter runs pre-login with no AppConfig singleton, so a surviving
# `AppConfig.` reference is not a warning — it is a ReferenceError that kills the
# binding it sits in. `durationScale` reached the greeter exactly this way and
# every animation duration in the login screen evaluated to undefined, because
# the substitution list above only knew about fontScale. Failing generation is
# the only place this can be caught before the pre-login screen.
if grep -n 'AppConfig' "$DST"/*.qml >/dev/null 2>&1; then
  echo "sync-ui.sh: FATAL — AppConfig survives in generated greeter files:" >&2
  grep -n 'AppConfig' "$DST"/*.qml >&2
  echo "The greeter has no AppConfig. Add a substitution for each reference above." >&2
  exit 1
fi

config_drift=0
for entry in "KeyboardLayoutService:services/KeyboardLayoutService.qml" "ConfigValidator:config/ConfigValidator.qml"; do
  name="${entry%%:*}"
  rel="${entry#*:}"
  generated="$(mktemp)"
  with_header < "$ROOT/src/core/$rel" > "$generated"
  destination="$SCRIPT_DIR/config/$name.qml"
  if [ "$CHECK" -eq 1 ]; then
    diff -q "$generated" "$destination" >/dev/null 2>&1 || config_drift=$((config_drift + 1))
  else
    cp "$generated" "$destination"
  fi
  rm -f "$generated"
done

if [ "$CHECK" -eq 1 ]; then
  drifted="$config_drift"
  for f in "$DST"/*; do
    name="$(basename "$f")"
    if ! diff -q "$f" "$REAL/$name" > /dev/null 2>&1; then
      drifted=$((drifted + 1))
      echo "  DRIFTED: ui/$name" >&2
    fi
  done
  echo "$drifted"
  [ "$drifted" -eq 0 ]
  exit $?
fi

echo "Done. Greeter UI kit regenerated in $DST"
